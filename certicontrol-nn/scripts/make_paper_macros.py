"""Write paper/results_macros.tex from the stored Dubins-car results."""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main():
    d = ROOT / "results" / "dubins_car"
    meta = json.loads((d / "certificate.json").read_text())
    s = meta["summary"]
    check = json.loads((d / "proof_check.json").read_text()) if (d / "proof_check.json").exists() else None
    ev = json.loads((d / "evaluation.json").read_text()) if (d / "evaluation.json").exists() else None
    rounds = sum(1 for h in meta["history"] if isinstance(h.get("round"), int))
    lm = s["leaves_by_method"]
    n = lambda x: f"{x:,}".replace(",", "{,}")
    vol = f"{100 * s['proven_volume_fraction']:.1f}\\%"
    if s["status"] == "CERTIFIED":
        abstract = (f"the loop certifies all four properties over the full 4-D domain after {rounds} CGIS rounds "
                    f"with {n(s['domain_leaves'])} proof leaves ({n(lm['z3'])} closed by Z3).")
        res = (f"CGIS certified P0--P3 after {rounds} rounds with {n(s['domain_leaves'])} domain leaves "
               f"({n(lm['crown'])} CROWN, {n(lm['z3'])} Z3); the independent checker "
               f"{'accepts' if check and check['ok'] else 'was run on'} the proof.")
    else:
        abstract = (f"the verifier proves the barrier conditions on {vol} of the domain volume and certifies $X_0\\subseteq\\C$, "
                    f"yet returns {s['counterexamples']} validated counterexamples that uniform sampling hits at a rate "
                    f"of only $\\sim\\!10^{{-5}}$ -- exactly the failure mode that motivates formal verification.")
        res = (f"After {rounds} CGIS rounds a re-verification that processes {n(s['domain_boxes_processed'])} boxes proves "
               f"P1--P2 on {vol} of $\\mathrm{{vol}}(D)$ ({n(s['domain_leaves'])} leaves, {n(lm['z3'])} closed by Z3) "
               f"and P0 on all of $X_0$ ({n(s['init_leaves'])} leaves), but stops after collecting "
               f"{s['counterexamples']} validated counterexamples, so the status is \\textsc{{falsified}} and no certificate "
               f"is issued. All violations sit on the edge of $\\C$ close to the obstacle at near-zero speed, where "
               f"$\\dot B$ can only be changed through $\\partial B/\\partial v$ and $\\partial B/\\partial\\theta$. "
               f"The learned policy is conservative: at $v=0.6$ the set $\\C$ is small (Fig.~\\ref{{fig:main}}) and "
               f"the controller mostly brakes to rest.")
    if ev:
        r = ev["rollouts"]
        ds = ev["dense_sampling"]
        res += (f" This failure is nearly invisible empirically: {n(ds['samples'])} uniform samples contain only "
                f"{ds['domain_violations']} violating states, and {r['X0']['rollouts'] + r['C']['rollouts']} rollouts "
                f"from $X_0$ and $\\C$ (10\\,s) never leave $\\C$.")
        if "counterexample_rollouts" in ev:
            c = ev["counterexample_rollouts"]
            res += (f" Rollouts started at verifier counterexamples, however, leave $\\C$ in {c['left_C']}/{c['rollouts']} "
                    f"cases (none reaches the obstacle), confirming that the violations are real invariance failures.")
    fig = "figures/dubins_slices.pdf"
    cap = (r"Dubins car: slices $(p_x,p_y)$ of $\C$ at headings $\theta\in\{0,\pi/2,\pi,-\pi/2\}$ for $v=0$ (top) "
           r"and $v=0.6$ (bottom); obstacle in red.")
    tex = "% auto-generated by scripts/make_paper_macros.py\n"
    tex += f"\\newcommand{{\\DubAbstract}}{{{abstract}}}\n"
    tex += f"\\newcommand{{\\DubResults}}{{{res}}}\n"
    tex += f"\\newcommand{{\\DubFigure}}{{{fig}}}\n"
    tex += f"\\newcommand{{\\DubFigCaption}}{{{cap}}}\n"
    (ROOT / "paper" / "results_macros.tex").write_text(tex)
    print(tex)


if __name__ == "__main__":
    main()
